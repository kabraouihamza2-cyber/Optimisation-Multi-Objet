def analyze_datasets(data_dir):
    """
        feature engineere + creates the ML csv train file using utils.py.
    """
    # makes sure that the file catalog is up to date.
    df = update_file_catalog(data_dir)



    # feature engineering:
    df["last_access_days_ago"] = (
        pd.Timestamp.now()
        - pd.to_datetime(df["last_access_date"])
    ).dt.days


    generate_ml_train_csv(df)
