def update_file_catalog(data_dir):
    """
       meme code de utils mais en preservant l'access frequency
    """
    try:
        df = pd.read_csv(catalog_path)
        frequences = df.set_index('file_id')['access_freq'].to_dict()
    except:
        frequences = {}

    rows = []

    for file in os.listdir(data_dir):
        f_path = os.path.join(data_dir,file)

        last_accesed = datetime.fromtimestamp(os.path.getatime(f_path))
        f_size = os.path.getsize(f_path)  # in bytes.
        f_type = os.path.splitext(file)[1].lower()


        # Id for files:       
        file_id, display_name = file.split("_", 1)


